pub unsafe fn br_handler(name: *const core::ffi::c_char) -> Option<BrSpecial> {
    for h in G_BR_HANDLERS {
        if libc::strcmp(h.name, name) == 0 {
            return Some(h.f);
        }
    }
    None
}
